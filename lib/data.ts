export function visibleMaz(day: DayData, mode: WeekMode): MazEvent[] {
  return day.maz
    .filter(e => mode === "exam" || !e.examOnly)
    .slice()
    .sort((a, b) => a.startsAt.localeCompare(b.startsAt));
}

export function visibleNotes(notes: DayNote[], mode: WeekMode): string[] {
  return notes
    .filter(n => (mode === "exam" ? !n.regularOnly : !n.examOnly))
    .map(n => (mode === "exam" ? n.examText ?? n.text : n.regularText ?? n.text));
}

export function emptyMazMessage(day: DayData, mode: WeekMode): string {
  if (day.key === "fri" && mode === "regular")
    return "در حالت نمایشیِ هفتهٔ بدون آزمون، کارت آزمون نمایش داده نمی‌شود؛ جمعه همچنان روز استراحت ۸ ساعته است.";
  if (day.maz.length === 0)
    return `در ${day.name} کلاس مازی در برنامهٔ ثابت نیست؛ روز طبق روتین پر می‌شود.`;
  return "با این فیلتر، کلاسی در این روز نیست.";
}

export function todayKey(): DayKey {
  const map: DayKey[] = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"];
  return map[new Date().getDay()]!;
}

export const toFa = (v: number | string): string =>
  String(v).replace(/\d/g, d => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]!);
